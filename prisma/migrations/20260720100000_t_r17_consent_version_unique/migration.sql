-- T-R17 (remediation of a T-38 QC finding, master-spec §9.2 / §16.3 "versioned"): purely additive.
-- No existing table, column, constraint, or enum is altered or dropped, and no existing row's
-- meaning changes.
--
-- Fixes a consent-version race: `MessagingConsentLedger.captureConsent`
-- (src/services/compliance/messaging-consent/messaging-consent-ledger.ts) computes the next
-- `ComplianceConsent.version` by reading the current-latest row and adding 1. Two concurrent
-- captures for the SAME (contact_id, consent_type) could both read the same "latest" and both
-- insert with the SAME next version number -- prior to this migration, nothing in the DB stopped
-- that. This adds a UNIQUE constraint on (contact_id, consent_type, version) so the loser of that
-- race gets a Prisma P2002 (which the ledger now catches and retries against the new current
-- version) instead of two rows silently sharing one version number.
--
-- NULL-safety (WP11 onboarding-consent, contact_id IS NULL, is NOT constrained by this -- and
-- must not be): Postgres's default unique-index semantics treat NULL as DISTINCT from every other
-- NULL (this is the standard default; the opt-in "NULLS NOT DISTINCT" behavior, PG 15+, is not
-- requested here), so a PLAIN unique constraint on a nullable column never fires for
-- `contact_id IS NULL` rows against each other -- exactly the WP11 onboarding-consent shape
-- (src/lib/onboarding/gdpr-consent.ts: contact_id always NULL, version always the default 1;
-- WP11's real versioning lives in ConsentManager's in-process Map, not this column). See
-- prisma/schema.prisma's ComplianceConsent doc comment for the full reasoning; a hand-authored
-- partial index (the `Subscription`/`Sponsorship` "one ACTIVE row" technique elsewhere in this
-- schema) is deliberately NOT used here -- it would be strictly more machinery for the same result,
-- since the race being fixed is specifically per-CONTACT (contact_id set), not per-null-subject.
--
-- Hand-authored, not generated by `prisma migrate dev`: no live Postgres connection is available
-- in this build environment (DATABASE_URL intentionally unset per build constraints), following
-- the same hand-authored-SQL convention established by 20260716120000_t12_account_security,
-- 20260717120000_t22_import_batch, 20260717150000_t23_memory_jogger_skip_count,
-- 20260718100000_t29r_contact_jurisdiction, 20260718180000_t34_learning_state_and_shift, and
-- 20260719100000_t38_optout_quiet_tcpa.

-- CreateIndex
CREATE UNIQUE INDEX "ComplianceConsent_contact_id_consent_type_version_key" ON "ComplianceConsent"("contact_id", "consent_type", "version");
